if let s = synthetic, !realRows.isEmpty {
    say("## Dataset: real DJ transitions (positives only)")
    say()
    let confident = realRows.filter { ($0.f["confidence"] ?? 0) >= 0.2 }
    say("\(realRows.count) transitions detected in \(Set(realRows.map(\.group)).count) human DJ sets, \(confident.count) with detection confidence ≥ 0.2. They have no bad examples, so the only question is how often each scorer would veto what a human DJ actually did. Models are trained on the whole synthetic set using only the features both sets carry.")
    say()
    let shared = s.features.filter { name in
        let finite = realRows.filter { ($0.f[name] ?? .nan).isFinite }.count
        return finite * 2 >= realRows.count && !name.hasPrefix("low") && !name.hasPrefix("mid") && !name.hasPrefix("high") || name == "lowOverlap"
    }
    say("Shared features: \(shared.joined(separator: ", ")).")
    say()
    let lm = train(s.rows, features: shared, learner: .logistic)
    let mm = train(s.rows, features: shared, learner: .mlp)
    say("| scorer | called good (all) | called good (confidence ≥ 0.2) |")
    say("|---|---|---|")
    func share(_ rows: [Row], _ f: (Row) -> Bool) -> String { pct(Double(rows.filter(f).count) / Double(max(1, rows.count))) }
    say("| 1 gates | \(share(realRows) { $0.gates.isEmpty }) | \(share(confident) { $0.gates.isEmpty }) |")
    if let lm { say("| 3 logistic (synthetic-trained) | \(share(realRows) { lm.score($0) >= 0.5 }) | \(share(confident) { lm.score($0) >= 0.5 }) |") }
    if let mm { say("| 4 MLP (synthetic-trained) | \(share(realRows) { mm.score($0) >= 0.5 }) | \(share(confident) { mm.score($0) >= 0.5 }) |") }
    if let lm { say("| 5 gates + logistic | \(share(realRows) { $0.gates.isEmpty && lm.score($0) >= 0.5 }) | \(share(confident) { $0.gates.isEmpty && lm.score($0) >= 0.5 }) |") }
    let sets = Set(realRows.map(\.group))
    let looPriors = realRows.map { r in Priors(realRows.filter { $0.group != r.group }).score(r) }
    say("| 6 real-set priors (leave one set out) | \(pct(Double(looPriors.filter { $0 >= 0.5 }.count) / Double(realRows.count))) | n/a |")
    say()
    var fired: [String: Int] = [:]
    for r in realRows { for g in r.gates { fired[g, default: 0] += 1 } }
    say("Gates that fire on human transitions: \(fired.isEmpty ? "none" : fired.sorted { $0.value > $1.value }.map { "\($0.key) \($0.value)" }.joined(separator: ", ")). Sets: \(sets.count).")
    say()
}

