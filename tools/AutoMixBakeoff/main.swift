say("## Cost")
say()
if let s = synthetic, let lm = train(s.rows, features: s.features, learner: .logistic), let mm = train(s.rows, features: s.features, learner: .mlp) {
    func time(_ f: () -> Void) -> Double {
        let start = Date()
        for _ in 0..<20_000 { f() }
        return Date().timeIntervalSince(start) / 20_000 * 1e6
    }
    let probe = s.rows[0]
    var sink = 0.0
    let tl = time { sink += lm.score(probe) }
    let tm = time { sink += mm.score(probe) }
    let tg = time { sink += Double(Gates.fired(AutoMixNetFeatures.vector(AutoMixNetObservation(moveType: "blend", blendBars: 16))).count) }
    let tp = time { sink += priors.score(probe) }
    func bytes(_ t: Trained) -> Int { (try? JSONEncoder().encode(t.net.export(featureNames: t.features, mean: t.standard.mean, scale: t.standard.scale)).count) ?? 0 }
    func params(_ t: Trained) -> Int { t.net.w.map(\.count).reduce(0, +) + t.net.b.map(\.count).reduce(0, +) }
    say("| scorer | inference per plan | parameters | exported size | training data |")
    say("|---|---|---|---|---|")
    say(String(format: "| gates | %.2f µs | 0 (thresholds) | in code | none |", tg))
    say(String(format: "| logistic | %.2f µs | %d | %d B JSON | labelled transitions, ~100 is enough to fit |", tl, params(lm), bytes(lm)))
    say(String(format: "| MLP 24-16 | %.2f µs | %d | %d B JSON | labelled transitions, wants many hundreds |", tm, params(mm), bytes(mm)))
    say(String(format: "| real-set priors | %.2f µs | %d | tiny | human DJ sets, no labels |", tp, priors.centre.count * 2))
    say("| Claude vision review | seconds and an API call per render | n/a | n/a | none, but needs a rendered PNG |")
    say("")
    if sink == .infinity { say("") }
}

