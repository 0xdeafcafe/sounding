let priors = Priors(realRows)

struct Contender {
    var name: String
    var scores: [Double]
    var threshold = 0.5
}

func faultName(_ r: Row) -> String { r.fault ?? "good" }

func report(_ d: BakeoffDataset) {
    let rows = d.rows
    let binary = rows.indices.filter { !rows[$0].borderline }
    let labels = binary.map { rows[$0].good }
    say("## Dataset: \(d.name)")
    say()
    let groups = Set(rows.map(\.group)).count
    say("n = \(rows.count) (\(rows.filter(\.good).count) good, \(rows.filter { !$0.good && !$0.borderline }.count) bad, \(rows.filter(\.borderline).count) borderline left out of the binary metrics). Leave-one-track-pair-out CV over \(groups) unordered pairs; A>B and B>A are in the same group.")
    say()
    let gates = gateScores(rows)
    let logistic = groupedScores(rows, features: d.features, learner: .logistic)
    let mlp = groupedScores(rows, features: d.features, learner: .mlp)
    var contenders = [
        Contender(name: "1 gates", scores: gates, threshold: 0.75),
        Contender(name: "3 logistic", scores: logistic),
        Contender(name: "4 MLP", scores: mlp),
        Contender(name: "5 gates + logistic", scores: vetoed(gates, logistic)),
        Contender(name: "5 gates + MLP", scores: vetoed(gates, mlp)),
        Contender(name: "6 real-set priors", scores: rows.map(priors.score))
    ]
    if !d.aiFeatures.isEmpty {
        let la = groupedScores(rows, features: d.features + d.aiFeatures, learner: .logistic)
        let ma = groupedScores(rows, features: d.features + d.aiFeatures, learner: .mlp)
        contenders.append(Contender(name: "8 logistic + AI", scores: la))
        contenders.append(Contender(name: "8 MLP + AI", scores: ma))
        contenders.append(Contender(name: "8 gates + logistic + AI", scores: vetoed(gates, la)))
    }
    for name in reviewers.keys.sorted() {
        contenders.append(Contender(name: "7 Claude \(name)", scores: rows.map { $0.reviewers[name] ?? .nan }))
    }

    say("### Judging")
    say()
    say("| contender | n | accuracy | AUC (95 % CI) | bad recall (95 % CI) | false alarms on good | Brier | ECE |")
    say("|---|---|---|---|---|---|---|---|")
    for c in contenders {
        let s = Score(binary.map { c.scores[$0] }, labels, threshold: c.threshold)
        guard s.n > 0 else { continue }
        let sub = binary.map { rows[$0] }
        let aucCI = bootstrap(sub) { idx in areaUnderCurve(idx.map { c.scores[binary[$0]] }, idx.map { labels[$0] }) }
        let recallCI = bootstrap(sub) { idx in Score(idx.map { c.scores[binary[$0]] }, idx.map { labels[$0] }, threshold: c.threshold).badRecall }
        say("| \(c.name) | \(s.n) | \(f3(s.accuracy)) | \(f3(s.auc)) \(aucCI.text) | \(f3(s.badRecall)) \(recallCI.text) | \(pct(s.falseAlarm)) | \(f3(s.brier)) | \(f3(s.ece)) |")
    }
    say()
    say("Gates use threshold 0.75 (any fired gate means bad); the rest use 0.5. Priors are a typicality score, not a probability, so their Brier and ECE are not meaningful.")
    say()

    say("Paired AUC differences, bootstrapped over track pairs (significant only when the interval excludes 0):")
    say()
    let byName = Dictionary(uniqueKeysWithValues: contenders.map { ($0.name, $0.scores) })
    var comparisons = [("3 logistic", "1 gates"), ("4 MLP", "3 logistic"), ("5 gates + logistic", "1 gates"), ("5 gates + MLP", "5 gates + logistic"), ("6 real-set priors", "1 gates")]
    if !d.aiFeatures.isEmpty { comparisons += [("8 logistic + AI", "3 logistic"), ("8 MLP + AI", "4 MLP")] }
    let sub = binary.map { rows[$0] }
    for (a, b) in comparisons {
        guard let sa = byName[a], let sb = byName[b] else { continue }
        let point = areaUnderCurve(binary.map { sa[$0] }, labels) - areaUnderCurve(binary.map { sb[$0] }, labels)
        let ci = bootstrap(sub) { idx in
            areaUnderCurve(idx.map { sa[binary[$0]] }, idx.map { labels[$0] }) - areaUnderCurve(idx.map { sb[binary[$0]] }, idx.map { labels[$0] })
        }
        say("- \(a) minus \(b): \(f3(point)) \(ci.text)\(ci.excludesZero ? "" : ", not significant")")
    }
    say()

    say("### Per-fault catch rate (share flagged bad)")
    say()
    let faults = Array(Set(binary.map { faultName(rows[$0]) })).sorted { ($0 == "good" ? "" : $0) < ($1 == "good" ? "" : $1) }
    let shown = contenders.filter { !$0.name.hasPrefix("7") || true }
    say("| fault | n | " + shown.map(\.name).joined(separator: " | ") + " |")
    say("|---|---|" + shown.map { _ in "---|" }.joined())
    for fault in faults {
        let idx = binary.filter { faultName(rows[$0]) == fault }
        let cells = shown.map { c -> String in
            let v = idx.map { c.scores[$0] }.filter(\.isFinite)
            guard !v.isEmpty else { return "n/a" }
            return pct(Double(v.filter { $0 < c.threshold }.count) / Double(v.count))
        }
        say("| \(fault == "good" ? "good (false alarms)" : fault) | \(idx.count) | " + cells.joined(separator: " | ") + " |")
    }
    say()

    say("### Choosing: best of each held-out pair's candidates")
    say()
    let ordered = Dictionary(grouping: rows.indices, by: { rows[$0].pair })
    say("\(ordered.count) ordered pairs. Each scorer picks its top candidate (out-of-fold scores, ties averaged). \"good\" is the label of the pick; \"passes gates\" means no hard gate fired. Lower is better for every metric.")
    say()
    say("| scorer | pairs | pick is good | passes gates | " + d.objectiveNames.joined(separator: " | ") + " |")
    say("|---|---|---|---|" + d.objectiveNames.map { _ in "---|" }.joined())
    func choose(_ name: String, _ pick: ([Int]) -> [Int]) {
        var good = 0.0, pass = 0.0, n = 0.0
        var sums = [String: Double](), counts = [String: Double]()
        for (_, idx) in ordered {
            let chosen = pick(idx)
            guard !chosen.isEmpty else { continue }
            let w = 1 / Double(chosen.count)
            for i in chosen {
                good += rows[i].good ? w : 0
                pass += rows[i].gates.isEmpty ? w : 0
                for k in d.objectiveNames { if let v = rows[i].objective[k], v.isFinite { sums[k, default: 0] += v * w; counts[k, default: 0] += w } }
            }
            n += 1
        }
        let cells = d.objectiveNames.map { f2((sums[$0] ?? .nan) / (counts[$0] ?? .nan)) }
        say("| \(name) | \(Int(n)) | \(pct(good / n)) | \(pct(pass / n)) | " + cells.joined(separator: " | ") + " |")
    }
    choose("random candidate") { $0 }
    choose("oracle (a good one, if any)") { idx in let g = idx.filter { rows[$0].good }; return g.isEmpty ? idx : g }
    if rows.contains(where: \.plannerPick) {
        choose("2 planner score (its top pick)") { idx in idx.filter { rows[$0].plannerPick } }
    }
    for c in contenders {
        choose(c.name) { idx in
            let v = idx.filter { c.scores[$0].isFinite }
            guard let best = v.map({ c.scores[$0] }).max() else { return [] }
            return v.filter { abs(c.scores[$0] - best) < 1e-9 }
        }
    }
    say()

    say("### Leakage ablation: drop the features that define each fault")
    say()
    say("Catch rate for that fault with all features, then with its features removed (grouped CV). A big drop means the model was reading the fault's own definition back.")
    say()
    say("| fault | n | removed | logistic all → ablated | MLP all → ablated | false alarms after (logistic / MLP) |")
    say("|---|---|---|---|---|---|")
    for fault in faults where fault != "good" {
        guard let drop = d.faultFeatures[fault] else { continue }
        let idx = binary.filter { faultName(rows[$0]) == fault }
        guard !idx.isEmpty else { continue }
        let kept = d.features.filter { !drop.contains($0) }
        let la = groupedScores(rows, features: kept, learner: .logistic)
        let ma = groupedScores(rows, features: kept, learner: .mlp)
        func rate(_ s: [Double]) -> String { pct(Double(idx.filter { s[$0] < 0.5 }.count) / Double(idx.count)) }
        let goods = binary.filter { rows[$0].good }
        func alarms(_ s: [Double]) -> String { pct(Double(goods.filter { s[$0] < 0.5 }.count) / Double(max(1, goods.count))) }
        say("| \(fault) | \(idx.count) | \(drop.joined(separator: ", ")) | \(rate(logistic)) → \(rate(la)) | \(rate(mlp)) → \(rate(ma)) | \(alarms(la)) / \(alarms(ma)) |")
    }
    say()
    let confounds = d.features.filter { $0.hasPrefix("move.") || $0 == "blendLength" }
    let allFaultFeatures = Set(d.faultFeatures.values.flatMap { $0 })
    for (title, removed) in [("move type and blend length", confounds), ("every fault-defining feature", Array(allFaultFeatures)), ("move type, blend length and every fault-defining feature", confounds + Array(allFaultFeatures))] {
        let kept = d.features.filter { !removed.contains($0) }
        guard !kept.isEmpty else { continue }
        let la = groupedScores(rows, features: kept, learner: .logistic)
        let ma = groupedScores(rows, features: kept, learner: .mlp)
        let sl = Score(binary.map { la[$0] }, labels), sm = Score(binary.map { ma[$0] }, labels)
        say("- Without \(title): logistic AUC \(f3(sl.auc)), bad recall \(f3(sl.badRecall)), false alarms \(pct(sl.falseAlarm)); MLP AUC \(f3(sm.auc)), bad recall \(f3(sm.badRecall)), false alarms \(pct(sm.falseAlarm)). Kept: \(kept.count) features.")
    }
    say()

    say("### Stricter split: leave one track out")
    say()
    say("Train only on pairs that do not involve track X, test on pairs that do. With four tracks this leaves three for training.")
    say()
    say("| held-out track | n test | logistic AUC | MLP AUC | gates AUC |")
    say("|---|---|---|---|---|")
    for t in trackIds {
        let test = binary.filter { rows[$0].tracks.contains(t) }
        let trainRows = rows.filter { !$0.tracks.contains(t) }
        guard !test.isEmpty, let lm = train(trainRows, features: d.features, learner: .logistic), let mm = train(trainRows, features: d.features, learner: .mlp) else { continue }
        let y = test.map { rows[$0].good }
        say("| \(t) | \(test.count) | \(f3(areaUnderCurve(test.map { lm.score(rows[$0]) }, y))) | \(f3(areaUnderCurve(test.map { mm.score(rows[$0]) }, y))) | \(f3(areaUnderCurve(test.map { gates[$0] }, y))) |")
    }
    say()
}

